const MS_PER_DAY = 86_400_000;

/**
 * Deterministic index for a Puerto Rico business date (YYYY-MM-DD).
 * Consecutive calendar days advance one step through the library before wrapping.
 */
export function getQuoteIndexForBusinessDate(
  businessDate: string,
  quoteCount: number = motivationalQuotes.length
): number {
  if (!Number.isFinite(quoteCount) || quoteCount <= 0) return 0;
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(businessDate.trim());
  if (!match) return 0;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  if (!year || month < 1 || month > 12 || day < 1 || day > 31) return 0;
  const days = Math.floor(Date.UTC(year, month - 1, day) / MS_PER_DAY);
  return ((days % quoteCount) + quoteCount) % quoteCount;
}

/**
 * Select the Quote of the Day for a Puerto Rico business date.
 * Same date → same quote; next date → next index (cycles through the library).
 */
export function getQuoteOfTheDay(businessDate: string): MotivationalQuote {
  const index = getQuoteIndexForBusinessDate(businessDate);
  const quote = motivationalQuotes[index];
  if (!quote?.text?.trim() || !quote.author?.trim()) {
    throw new Error('Invalid motivational quote at selected index');
  }
  return { text: quote.text.trim(), author: quote.author.trim() };
}

/** Format the Quote of the Day block for the Daily Summary iMessage. */
export function formatQuoteOfTheDaySection(quote: MotivationalQuote): string {
  return [
    '━━━━━━━━━━━━━━',
    '',
    '💡 Quote of the Day',
    `“${quote.text}”`,
    `— ${quote.author}`,
  ].join('\n');
}
